class DatamapIter:

    def __init__(self, node: CMNode, data):
        self.datamap = {}
        node.datamap._datamap = self.datamap  # type: ignore
        self.diter = iter(data)

    def __next__(self):
        v = next(self.diter)
        self.datamap[LOW] = v[0]
        self.datamap[CLOSE] = v[1]
        self.datamap[HIGH] = v[2]
